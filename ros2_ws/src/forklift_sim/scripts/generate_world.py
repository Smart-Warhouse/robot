#!/usr/bin/env python3
"""Gazebo world + Nav2 occupancy map of the mini warehouse from the server's warehouse_map.yaml (EN-11, AI-01, B5).

    python generate_world.py [--map backend/app/warehouse_map.yaml] [--out ../worlds/warehouse.sdf]
                             [--map-out ../maps/warehouse_sim]

World: boundary walls around width_m x height_m (EN-07: taller than the LiDAR + 5 cm), racks as boxes from the `rack`
zones, flat coloured patches for the other zones. Systems use the Gazebo Fortress names (`ignition-gazebo-*`), the
Gazebo that ROS 2 Humble ships with (ros-humble-ros-gz); see docs/19-gazebo-sim.md for Harmonic.
Map: the same walls and racks as an occupancy grid (PGM + map_server YAML) for the `localization:=truth` mode of
sim.launch.py, which serves it instead of building one with slam_toolbox.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
WORKSPACE = Path(os.environ["SW_WORKSPACE"]) if os.environ.get("SW_WORKSPACE") else HERE.parents[4]  # holds the robot and backend repos
DEFAULT_MAP = WORKSPACE / "backend" / "app" / "warehouse_map.yaml"
DEFAULT_OUT = HERE.parent / "worlds" / "warehouse.sdf"
DEFAULT_MAP_OUT = HERE.parent / "maps" / "warehouse_sim"
WALL_H = 0.45            # LiDAR at 0.36 m (dimensions.yaml laser_z) + margin (EN-07)
WALL_T = 0.02
RACK_H = 0.15            # two levels (0 and 60 mm) + top — PLACEHOLDER until the real racks are measured
MAP_MARGIN = 0.1         # occupancy map border outside the walls (m)
ZONE_COLOURS = {"dock_in": "0.2 0.6 0.9 1", "dock_out": "0.2 0.8 0.4 1", "staging": "0.9 0.8 0.2 1",
                "charge": "0.3 0.3 0.9 1", "pedestrian": "0.9 0.5 0.1 1", "keepout": "0.8 0.1 0.1 1"}
SYS = "ignition-gazebo-{0}-system", "ignition::gazebo::systems::{1}"   # Fortress (gz-sim 6) plugin names


def plugin(lib: str, cls: str, body: str = "") -> str:
    fn, name = SYS[0].format(lib), SYS[1].format(lib, cls)
    head = f'<plugin filename="{fn}" name="{name}"'
    return f"{head}>{body}</plugin>" if body else f"{head}/>"


def box(name: str, x: float, y: float, z: float, sx: float, sy: float, sz: float, rgba: str,
        collide: bool = True) -> str:
    col = (f"""
        <collision name="collision"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry></collision>"""
           if collide else "")
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} {z:.3f} 0 0 0</pose>
      <link name="link">{col}
        <visual name="visual">
          <geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry>
          <material><ambient>{rgba}</ambient><diffuse>{rgba}</diffuse></material>
        </visual>
      </link>
    </model>"""


def bbox(poly: list[list[float]]) -> tuple[float, float, float, float]:
    xs, ys = [p[0] for p in poly], [p[1] for p in poly]
    return min(xs), min(ys), max(xs), max(ys)


def racks(wh: dict) -> list[tuple[str, float, float, float, float]]:
    return [(z["id"], *bbox(z["polygon"])) for z in wh.get("zones", []) if z["kind"] == "rack"]


def world_sdf(wh: dict) -> str:
    W, H = float(wh["width_m"]), float(wh["height_m"])
    models = [
        box("wall_south", W / 2, -WALL_T / 2, WALL_H / 2, W + 2 * WALL_T, WALL_T, WALL_H, "0.7 0.7 0.7 1"),
        box("wall_north", W / 2, H + WALL_T / 2, WALL_H / 2, W + 2 * WALL_T, WALL_T, WALL_H, "0.7 0.7 0.7 1"),
        box("wall_west", -WALL_T / 2, H / 2, WALL_H / 2, WALL_T, H, WALL_H, "0.7 0.7 0.7 1"),
        box("wall_east", W + WALL_T / 2, H / 2, WALL_H / 2, WALL_T, H, WALL_H, "0.7 0.7 0.7 1"),
    ]
    for z in wh.get("zones", []):
        x0, y0, x1, y1 = bbox(z["polygon"])
        cx, cy, sx, sy = (x0 + x1) / 2, (y0 + y1) / 2, x1 - x0, y1 - y0
        if z["kind"] == "rack":
            models.append(box(f"rack_{z['id']}", cx, cy, RACK_H / 2, sx, sy, RACK_H, "0.55 0.35 0.2 1"))
        elif z["kind"] in ZONE_COLOURS:
            models.append(box(f"zone_{z['id']}", cx, cy, 0.0005, sx, sy, 0.001, ZONE_COLOURS[z["kind"]], False))
    body = "".join(models)
    return f"""<?xml version="1.0"?>
<!-- GENERATED by forklift_sim/scripts/generate_world.py from backend/app/warehouse_map.yaml — do not edit;
     re-run the script after changing the map. Mini warehouse {W} x {H} m (1:14), map frame = world frame.
     Gazebo Fortress (ROS 2 Humble's ros_gz); the forklifts are spawned by launch/sim.launch.py. -->
<sdf version="1.9">
  <world name="warehouse">
    <physics name="2ms" type="ignored">
      <max_step_size>0.002</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    {plugin("physics", "Physics")}
    {plugin("user-commands", "UserCommands")}
    {plugin("scene-broadcaster", "SceneBroadcaster")}
    {plugin("sensors", "Sensors", "<render_engine>ogre2</render_engine>")}
    {plugin("imu", "Imu")}

    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>3 2 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <direction>-0.3 0.2 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry></collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry>
          <material><ambient>0.85 0.85 0.8 1</ambient><diffuse>0.85 0.85 0.8 1</diffuse></material>
        </visual>
      </link>
    </model>
{body}
  </world>
</sdf>
"""


def occupancy(wh: dict) -> tuple[bytes, str]:
    """(PGM bytes, map_server YAML) of walls (everything outside the floor) and racks; 0 = occupied, 254 = free."""
    res = float(wh.get("resolution_m", 0.02))
    W, H = float(wh["width_m"]), float(wh["height_m"])
    ox = oy = -MAP_MARGIN
    nx, ny = round((W + 2 * MAP_MARGIN) / res), round((H + 2 * MAP_MARGIN) / res)
    blocked = [(r[1], r[2], r[3], r[4]) for r in racks(wh)]
    rows = []
    for j in range(ny - 1, -1, -1):           # PGM: first row = top (max y)
        y = oy + (j + 0.5) * res
        row = bytearray()
        for i in range(nx):
            x = ox + (i + 0.5) * res
            occ = not (0.0 < x < W and 0.0 < y < H) or any(x0 <= x <= x1 and y0 <= y <= y1
                                                             for x0, y0, x1, y1 in blocked)
            row.append(0 if occ else 254)
        rows.append(bytes(row))
    pgm = f"P5\n# generated by forklift_sim/scripts/generate_world.py\n{nx} {ny}\n255\n".encode() + b"".join(rows)
    meta = (f"# generated by forklift_sim/scripts/generate_world.py from warehouse_map.yaml (walls + racks)\n"
            f"image: warehouse_sim.pgm\nmode: trinary\nresolution: {res}\norigin: [{ox}, {oy}, 0.0]\nnegate: 0\n"
            f"occupied_thresh: 0.65\nfree_thresh: 0.196\n")
    return pgm, meta


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--map", type=Path, default=DEFAULT_MAP)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--map-out", type=Path, default=DEFAULT_MAP_OUT, help="occupancy map path without extension")
    a = ap.parse_args()
    wh = yaml.safe_load(a.map.read_text(encoding="utf-8"))
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_bytes(world_sdf(wh).encode("utf-8"))
    pgm, meta = occupancy(wh)
    a.map_out.parent.mkdir(parents=True, exist_ok=True)
    a.map_out.with_suffix(".pgm").write_bytes(pgm)
    a.map_out.with_suffix(".yaml").write_bytes(meta.encode("utf-8"))
    print(a.out, a.map_out)


if __name__ == "__main__":
    main()
