#!/usr/bin/env python3
"""Generate the Nav2 costmap-filter masks (NV-08) from the server's warehouse_map.yaml zones.

    python make_filter_masks.py [--map ../../../../backend/app/warehouse_map.yaml] [--out ../maps]

  keepout_mask.pgm/.yaml : zones of kind `keepout` and `pedestrian` -> lethal (KeepoutFilter, trinary)
  speed_mask.pgm/.yaml   : zones listed in SPEED_ZONES -> speed limit in % of max (SpeedFilter type 1, scale mode)
The mask frame is the map frame = the warehouse frame (origin bottom-left); slam_mapping.yaml starts the map at the
same origin, so masks and SLAM map line up. Pure Python (no numpy) so it runs anywhere.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
DEFAULT_MAP = HERE.parents[3] / "backend" / "app" / "warehouse_map.yaml"
DEFAULT_OUT = HERE.parent / "maps"
KEEPOUT_KINDS = ("keepout", "pedestrian")
SPEED_ZONES = {"charge": 50, "staging": 50, "dock_in": 50, "dock_out": 50}  # percent of the maximum speed


def point_in_polygon(x: float, y: float, poly: list[list[float]]) -> bool:
    inside = False
    n = len(poly)
    for i in range(n):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % n]
        if (y1 > y) != (y2 > y):
            xin = x1 + (y - y1) * (x2 - x1) / (y2 - y1)
            if x < xin:
                inside = not inside
    return inside


def rasterize(wh: dict, values: dict[str, int], default: int) -> tuple[int, int, list[list[int]]]:
    """Grid (rows top -> bottom) of pixel values; a cell takes the value of the zone containing its centre."""
    res = float(wh.get("resolution_m", 0.02))
    w = int(round(float(wh["width_m"]) / res))
    h = int(round(float(wh["height_m"]) / res))
    grid = [[default] * w for _ in range(h)]
    for z in wh.get("zones", []):
        if z["kind"] not in values:
            continue
        val = values[z["kind"]]
        poly = z["polygon"]
        for r in range(h):
            y = (h - 1 - r + 0.5) * res
            row = grid[r]
            for c in range(w):
                if point_in_polygon((c + 0.5) * res, y, poly):
                    row[c] = val
    return w, h, grid


def write_pgm(path: Path, w: int, h: int, grid: list[list[int]]) -> None:
    data = bytearray(f"P5\n{w} {h}\n255\n".encode())
    for row in grid:
        data.extend(bytes(row))
    path.write_bytes(bytes(data))


def read_pgm(path: Path) -> tuple[int, int, bytes]:
    raw = path.read_bytes()
    parts = raw.split(b"\n", 3)
    assert parts[0] == b"P5", "not a binary PGM"
    w, h = (int(v) for v in parts[1].split())
    return w, h, parts[3]


def percent_to_pixel(percent: int) -> int:
    """Scale mode with free_thresh 0 / occupied_thresh 1: occupancy = round(100 * (255 - pixel) / 255)."""
    return int(round(255 * (1 - percent / 100.0)))


def generate(map_file: Path, out: Path) -> dict[str, Path]:
    wh = yaml.safe_load(map_file.read_text(encoding="utf-8"))
    out.mkdir(parents=True, exist_ok=True)
    res = float(wh.get("resolution_m", 0.02))
    files = {}
    w, h, grid = rasterize(wh, {k: 0 for k in KEEPOUT_KINDS}, 255)
    write_pgm(out / "keepout_mask.pgm", w, h, grid)
    (out / "keepout_mask.yaml").write_text(
        "# generated by scripts/make_filter_masks.py from warehouse_map.yaml zones (keepout, pedestrian)\n"
        f"image: keepout_mask.pgm\nmode: trinary\nresolution: {res}\norigin: [0.0, 0.0, 0.0]\n"
        "negate: 0\noccupied_thresh: 0.65\nfree_thresh: 0.196\n", newline="\n")
    files["keepout"] = out / "keepout_mask.yaml"
    w, h, grid = rasterize(wh, {k: percent_to_pixel(v) for k, v in SPEED_ZONES.items()}, 255)
    write_pgm(out / "speed_mask.pgm", w, h, grid)
    (out / "speed_mask.yaml").write_text(
        "# generated by scripts/make_filter_masks.py: speed limit in % of max (white = no limit)\n"
        f"image: speed_mask.pgm\nmode: scale\nresolution: {res}\norigin: [0.0, 0.0, 0.0]\n"
        "negate: 0\noccupied_thresh: 1.0\nfree_thresh: 0.0\n", newline="\n")
    files["speed"] = out / "speed_mask.yaml"
    return files


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--map", type=Path, default=DEFAULT_MAP)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    a = ap.parse_args()
    for k, p in generate(a.map, a.out).items():
        print(f"{k}: {p}")


if __name__ == "__main__":
    main()
